function questionsFor(bank,kind){
 const groups=Object.entries(bank).map(([dimension,pair])=>{
  const items=[]
  for(let i=0;i<Math.max(pair.positive.length,pair.negative.length);i++){
   if(pair.positive[i])items.push({id:kind+'-'+dimension+'-p'+i,text:pair.positive[i],dimension,axis:dimension,reverse:false})
   if(pair.negative[i])items.push({id:kind+'-'+dimension+'-n'+i,text:pair.negative[i],dimension,axis:dimension,reverse:true})
  }
  return items
 })
 const questions=[]
 for(let i=0;i<Math.max(...groups.map(group=>group.length));i++)for(const group of groups)if(group[i])questions.push(group[i])
 return questions
}
