const fs=require('node:fs'),http=require('node:http'),assert=require('node:assert/strict')
const {parse,compileTemplate}=require(process.cwd()+'/绿岛/node_modules/@vue/compiler-sfc')
const {chromium}=require('playwright')
const read=p=>fs.readFileSync(p,'utf8')
const files=['绿岛/pages/index/index.vue','绿岛/components/CountdownSwitch.vue','绿岛/pages/messages/index.vue']
const bundles=files.map((p,i)=>{
 const d=parse(read(p)).descriptor
 let script=d.script.content.replace(/^\s*import\s+[\s\S]*?from\s+['"][^'"]+['"]\s*;?/gm,'').replace('export default','return')
 const compiled=compileTemplate({source:d.template.content,id:'test'+i,compilerOptions:{isCustomElement:t=>['view','text','image'].includes(t)}})
 assert.equal(compiled.errors.length,0,JSON.stringify(compiled.errors))
 return {script,render:compiled.code.replace(/from "vue"/g,'from "/vue.js"').replace('export function render','function render')+';export default render',css:d.styles.map(x=>x.content.replace(/@import[^;]+;/g,'')).join('\n')}
})
const html='<!doctype html><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#fdfdfb;font-family:Arial}view{display:block}button{font:inherit;box-sizing:border-box}button:after{border:0}'+bundles.map(x=>x.css).join('\n')+'</style><div id="app"></div><script type="module" src="/preview.js"></script>'
const preview=read('tools/message-preview-client.js').replace('__BUNDLES__',JSON.stringify(bundles)).replace('__NOTIFICATION_SOURCE__',JSON.stringify(read('绿岛/utils/notifications.js').replace(/^import .*$/gm,'').replace(/^export /gm,'')))
const routes={'/':html,'/preview.js':preview,'/vue.js':read('绿岛/node_modules/vue/dist/vue.esm-browser.prod.js'),'/engine.js':read('绿岛/utils/engine.js'),'/wishlist.js':read('绿岛/utils/wishlist.js'),'/actions.js':read('绿岛/utils/action-navigation.js'),'/navigation.js':read('绿岛/utils/message-navigation.js'),'/membership.js':read('绿岛/utils/membership.js')}
bundles.forEach((x,i)=>routes['/render'+i+'.js']=x.render)
;(async()=>{
 const server=http.createServer((req,res)=>{const p=new URL(req.url,'http://localhost').pathname;if(!routes[p]){res.writeHead(404).end();return}res.writeHead(200,{'Content-Type':p==='/'?'text/html; charset=utf-8':'text/javascript; charset=utf-8'}).end(routes[p])}).listen(0,'127.0.0.1')
 await new Promise(r=>server.once('listening',r))
 const browser=await chromium.launch({headless:true})
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:'+server.address().port);await page.waitForFunction(()=>window.ready)
  await page.evaluate(()=>window.prepare())
  assert.equal(await page.locator('.message-dot').count(),1)
  assert.equal(await page.locator('.account-sync-banner').count(),0)
  const metrics=await page.locator('.message-entry').evaluate(el=>{const s=getComputedStyle(el),r=el.getBoundingClientRect(),hit=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2);return {border:s.borderWidth,bg:s.backgroundColor,width:r.width,height:r.height,hit:el===hit||el.contains(hit)}})
  assert(metrics.hit&&metrics.width>=44&&metrics.height>=44&&metrics.border==='0px'&&metrics.bg==='rgba(0, 0, 0, 0)',JSON.stringify(metrics))
  const png=await page.screenshot({type:'jpeg',quality:80});console.log('HOME_PREVIEW_BASE64='+png.toString('base64'))
  await page.locator('.message-entry').click();await page.locator('.messages-page').waitFor()
  assert.match(await page.locator('.message-row').innerText(),/经验已到账/)
  await page.locator('.read-all').click()
  assert.equal(await page.locator('.unread-dot').count(),0)
  await page.locator('.messages-head .back').click();await page.locator('.home-view').waitFor()
  assert.equal(await page.locator('.message-dot').count(),0)
  await page.evaluate(()=>window.breakCache=true)
  await page.locator('.message-entry').click();await page.locator('.messages-page').waitFor()
  await page.locator('.messages-head .back').click();await page.locator('.home-view').waitFor()
  await page.evaluate(()=>{window.breakCache=false;window.failNav=true})
  await page.locator('.message-entry').click()
  assert(await page.evaluate(()=>window.notes.some(x=>x.includes('无法打开消息'))))
  await page.evaluate(()=>{window.failNav=false;window.state.cloudSync.status='error'})
  await page.locator('.account-sync-banner').waitFor()
  await page.locator('.countdown-switch-option').nth(1).click()
  assert.equal(await page.evaluate(()=>window.state.homeCountdown),'goal')
  assert.equal(await page.locator('.countdown-switch-option.selected').innerText(),'我的目标')
  assert.equal(await page.evaluate(()=>window.membership()),'有效期至 2030年11月12日')
  assert.equal(errors.length,0,errors.join('\n'))
  console.log('Real SFC browser checks passed: bell hit target, inbox open/read/back, broken cache, failure feedback, quiet pending, mode switch, Chinese membership')
 }finally{await browser.close();await new Promise(r=>server.close(r))}
})().catch(e=>{console.error(e);process.exit(1)})
